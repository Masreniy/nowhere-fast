-- Ватикан в справочнике стран: координаты руками, контура нет.
--
-- ПОЧЕМУ ЭТА СТРОКА ЗАВОДИТСЯ ОТДЕЛЬНО. Очертания стран приходят из Natural
-- Earth в масштабе 1:50 млн (ADR-0010). Ватикана там нет вовсе: 0,44 км² —
-- меньше разрешения карты. Генератор `tools/geo/build-reference-sql.js`
-- честно его пропускает и пишет об этом в манифест
-- (`countriesSkippedNoGeometry: ["VA"]`), поэтому в файлах `countries-*.sql`
-- строки `VA` нет и не будет.
--
-- ПОЧЕМУ ВСЁ-ТАКИ ЗАВОДИМ. Решение владельца 17.09.2026:
--
--   > первый, путешествиники туда тоже ездят когда посещают близжайшию страну
--
-- То есть Ватикан нужен как место назначения, а не как закрашенный контур:
-- человек ищет его в поиске, попадая в Рим. Это ровно то, для чего
-- справочник и существует.
--
-- ЧТО ЭТО ЗНАЧИТ НА ПРАКТИКЕ. Ватикан **не выбирается кликом по глобусу** —
-- выбор идёт по контуру, а контура нет; клик по этому месту выберет Италию.
-- Он находится поиском, и камера летит к настоящей точке. Это известная
-- и принятая цена, а не недоделка.
--
-- ДО ЭТОЙ ПРАВКИ строка лежала с нулевыми координатами — 0°, 0°, то есть
-- в Атлантике у берегов Африки, — и поиск уводил камеру в океан. Нашлось
-- сверкой `tools/geo/verify-countries.js`: она считает только те страны,
-- что есть в источнике, и Ватикан в её отчёт не попадает вовсе. Именно
-- поэтому такая строка и должна быть описана здесь, а не жить молча в базе.
--
-- КООРДИНАТЫ. 41.9029° с. ш., 12.4534° в. д. — общепринятый центр
-- Ватикана. `spread` 0.4 — тот же нижний предел, что генератор ставит
-- прочим крошечным территориям (Монако, Сан-Марино, Науру). `land_share`
-- ноль, как у них же.
--
-- ПОВТОРНЫЙ ЗАПУСК БЕЗОПАСЕН. `--force` у загрузчика справочника эту строку
-- не тронет: её нет в источнике. А вот полная перезаливка с очисткой
-- таблицы её потеряет — тогда нужно применить этот файл заново.
--
-- Применён 17.09.2026.


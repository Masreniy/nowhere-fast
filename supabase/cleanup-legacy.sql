-- ПРИМЕНЕНО 16.09.2026 по прямому решению владельца.
--
-- В отличие от schema.sql и policies.sql, этот файл УДАЛЯЕТ. Он оставлен
-- в репозитории как запись о том, что именно было убрано и почему: удалённое
-- не видно в схеме, а вопрос «а куда делась таблица users» возникнет.
--
-- Операторы блоков 1, 4 и 5 идемпотентны. Блок 2 адресный — удаляет строку
-- по конкретному id. Блок 6 БЫЛ написан как общее условие «любой маршрут без
-- дней» и потому при повторном запуске снял бы с публикации ещё и будущие
-- маршруты, которые просто не успели наполнить. Исправлено 16.09.2026:
-- теперь он тоже адресный. Прежняя формулировка сохранена в комментарии.

-- ---------------------------------------------------------------------------
-- Блок 1. Таблицы-призраки — удалены
--
-- В базе лежали четыре таблицы, которых нет ни в schema.sql, ни в коде:
--
--   users           — 0 строк, колонка password_hash
--   trips           — 0 строк
--   trip_activities — 0 строк
--   trip_packing    — 0 строк
--
-- Проверено перед удалением: ни одного обращения к ним во всех .html и .js
-- (грепом по trips, trip_activities, trip_packing, from('users'), password_hash).
--
-- Почему удалены, а не оставлены: password_hash — след самодельного входа.
-- Проект договорился делать аутентификацию через Supabase Auth
-- (docs/FOUNDATION.md), а своя таблица паролей — приглашение однажды
-- «дописать вход по-быстрому» и хранить пароли самому.
--
-- Порядок по зависимостям: trip_* ссылаются на trips, trips — на users.

drop table if exists public.trip_packing;
drop table if exists public.trip_activities;
drop table if exists public.trips;
drop table if exists public.users;

-- ---------------------------------------------------------------------------
-- Блок 2. Задвоенный маршрут — удалён
--
-- В route_templates было три маршрута, из них два — один и тот же маршрут,
-- заведённый дважды с разницей в четверть часа:
--
--   6cbc3c04…  «за 3 дня: классика», создан 22:12 — 6 дней, каждый записан дважды
--   4c7a5fdf…  «за 3 дня: классика», создан 22:27 — 3 дня, целый
--
-- Из-за задвоения страница города показывала шесть дней вместо трёх.
--
-- Перед удалением содержимое сверено запросом except в обе стороны:
-- 12 уникальных активностей в обеих копиях, различий нет ни в одном поле
-- (name, description, location, duration_minutes, type). Описание, days_count
-- и difficulty у маршрутов тоже совпадали.
--
-- Удалён более ранний испорченный импорт. Дни и активности ушли каскадом.

delete from public.route_templates
 where id = '6cbc3c04-781b-49ff-8338-f854f988a225';

-- ---------------------------------------------------------------------------
-- Блок 3. Уникальность дня внутри маршрута — включена
--
-- Ограничение объявлено в schema.sql и добавлено там же явным alter после
-- этой чистки. Запускать только после блока 2, иначе оператор упадёт.

-- см. supabase/schema.sql, блок «Что проглотил create table if not exists»

-- ---------------------------------------------------------------------------
-- Блок 4. Дублирующие колонки координат — удалены
--
-- В cities координаты лежали в двух парах колонок: coordinates_lat/lng
-- (numeric, старые, заполненные) и lat/lng (double precision, из schema.sql).
-- Значения перенесены в lat/lng, код и схема работают только с ними.
-- Проверено грепом: coordinates_* не упоминаются нигде в .html и .js.

alter table public.cities drop column if exists coordinates_lat;
alter table public.cities drop column if exists coordinates_lng;

-- ---------------------------------------------------------------------------
-- Блок 5. Опечатка в названии города — исправлена
--
-- Город в cities записан верно — «Гуанчжоу». Тексты маршрутов, дней и
-- активностей писали «Гуанджоу»: 3 названия маршрутов, 3 описания, 3 названия
-- дней, 3 описания дней, 6 названий активностей, 9 описаний.

update public.route_templates
   set name = replace(name, 'Гуанджоу', 'Гуанчжоу'),
       description = replace(description, 'Гуанджоу', 'Гуанчжоу')
 where name like '%Гуанджоу%' or description like '%Гуанджоу%';

update public.route_template_days
   set name = replace(name, 'Гуанджоу', 'Гуанчжоу'),
       description = replace(description, 'Гуанджоу', 'Гуанчжоу')
 where name like '%Гуанджоу%' or description like '%Гуанджоу%';

update public.route_template_activities
   set name = replace(name, 'Гуанджоу', 'Гуанчжоу'),
       description = replace(description, 'Гуанджоу', 'Гуанчжоу')
 where name like '%Гуанджоу%' or description like '%Гуанджоу%';

-- ---------------------------------------------------------------------------
-- Блок 6. Пустой маршрут — снят с публикации, НЕ удалён
--
-- Маршрут «Гуанчжоу за 5 дней: максимум впечатлений» обещает days_count = 5,
-- а дней и активностей у него ноль. Опубликованный, он показывал посетителю
-- пустоту.
--
-- Удалять не стали: в отличие от задвоенного импорта, это похоже на
-- незаконченный черновик, а не на мусор. Снятие публикации обратимо одним
-- флагом — вернуть можно, набив дни.

-- Исправлено 16.09.2026. Было:
--
--   update public.route_templates set is_published = false
--    where id not in (select distinct route_template_id from public.route_template_days);
--
-- Такой оператор снимает с публикации ЛЮБОЙ маршрут без дней — в том числе тот,
-- который автор только что завёл и ещё не успел наполнить. Файл при этом
-- обещал, что повторный запуск безопасен. Обещание было неверным.

update public.route_templates
   set is_published = false
 where id = '77efaab4-d806-4283-bcd1-e25adbb96108';

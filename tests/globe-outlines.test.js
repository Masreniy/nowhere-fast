/** Поднимает чистый документ и загружает в него outlines.js. */
function setup() {
    const dom = new JSDOM('<!doctype html><html><body></body></html>', {
        runScripts: 'outside-only',
    });
    const win = dom.window;
    win.eval(fs.readFileSync(path.join(ROOT, 'assets/js/globe/outlines.js'), 'utf8'));
    return win.NF.globeOutlines;
}

/** Индекс страны → её код: утверждения читаются кодом, а не номером строки. */
function codeAt(index, lat, lng, list) {
    const found = index.countryAt(lat, lng);
    return found < 0 ? null : list[found].code;
}

function build(outlines, list) {
    return outlines.build(list);
}


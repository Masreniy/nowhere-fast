/**
 * Синтетическая полярная страна: берег по параллели -70° и замыкание вдоль
 * самого полюса, как в исходных данных у Антарктиды. В плоскости
 * широта-долгота такой контур не замкнут, и без полярной проекции проверка
 * «точка внутри» отвечает наугад.
 */
function polarCountry() {
    const coast = [];
    const closure = [];
    for (let lon = -180; lon < 180; lon += 5) {
        coast.push([lon, -70]);
        closure.push([lon, -89.999]);
    }
    coast.push([-180, -70]);
    closure.push([-180, -89.999]);
    return {
        code: 'XX',
        outline: { type: 'MultiPolygon', coordinates: [[closure, coast]] },
    };
}


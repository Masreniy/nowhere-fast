/**
 * Проверка контуров стран: страна по точке, границы, полигон для подъёма.
 *
 * Зачем этот тест. На глобусе клик и наведение отвечают на вопрос «что это за
 * страна» по контурам из базы. Наивная проверка «точка в многоугольнике» врёт
 * в трёх местах сразу — на линии перемены дат, у полюса и на дырках внутри
 * страны, — и врёт молча: человек кликает по Лесото, открывается ЮАР.
 *
 * Данные. Контуры настоящие: Natural Earth 1:50 млн через world-atlas, те же,
 * что уезжают в базу. Здесь они прорежены (Дуглас-Пекер, допуск от 0,04° до 1°)
 * до полутысячи точек на пять стран — файл теста не должен весить мегабайт.
 * Из-за прореживания проверяются только точки, заведомо далёкие от береговой
 * линии; «в километре от границы» такой выжимкой проверять нельзя.
 *
 * Полное покрытие — 241 страна, 580 колец — прогонялось отдельно при переносе:
 * все проверки ниже проходят и на нём, и лишних стран не появляется.
 *
 * Запуск:  npm test
 */
const test = require('node:test');

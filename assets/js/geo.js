/**
 * Геометрия на сфере: то, что нужно всем, кто считает расстояния.
 *
 * Зачем этот файл появился. Формула гаверсинуса разошлась по проекту тремя
 * копиями: в планировщике, в точке отсчёта и в сцене глобуса. Комментарий
 * в origin.js прямо говорил: «третья копия означает, что пора заводить общий
 * помощник, а не копировать снова», — и следующим же коммитом появилась
 * третья копия. Правило проекта (coding-style.md) на этот счёт однозначно,
 * и здесь оно исполнено.
 *
 * Почему копии вообще были законны до сих пор: каждая лежала приватно внутри
 * своего модуля, наружу не отдавалась, а модули подключаются независимо друг
 * от друга — планировщик живёт без глобуса, глобус без планировщика. Но
 * формула одна, и разъехаться ей нельзя: расстояние, посчитанное по-разному
 * на разных страницах, — это противоречие на глазах у человека.
 *
 * Подключается ПЕРВЫМ из наших модулей, сразу после config.js: от него
 * зависят и planner.js, и origin.js, и сцена.
 */
window.NF = window.NF || {};

NF.geo = (function () {
    'use strict';

    /**
     * Средний радиус Земли, км.
     *
     * Земля не шар, и по меридиану радиус на 21 км меньше, чем по экватору.
     * Среднее даёт ошибку до 0,3 % — для «далеко или близко» это пренебрежимо,
     * для навигации недопустимо. Мы считаем первое.
     */
    const EARTH_RADIUS_KM = 6371;

    /** Градусы в радианы. */
    const DEG = Math.PI / 180;

    /**
     * Расстояние по дуге большого круга, км.
     *
     * Через линию перемены дат работает без оговорок: формула оперирует
     * разностью долгот через косинус, и скачок с 179 на -179 в ней
     * не отличается от любого другого шага.
     *
     * Это расстояние по дуге, а не по дороге. Для «долететь» годится,
     * для «доехать» — нет.
     */
    function haversineKm(aLat, aLng, bLat, bLng) {
        const dLat = (bLat - aLat) * DEG;
        const dLng = (bLng - aLng) * DEG;
        const h = Math.sin(dLat / 2) * Math.sin(dLat / 2) +
            Math.cos(aLat * DEG) * Math.cos(bLat * DEG) *
            Math.sin(dLng / 2) * Math.sin(dLng / 2);
        // Math.min(1, ...) не украшение: при совпадающих точках накопленная
        // погрешность даёт корень чуть больше единицы, и asin возвращает NaN.
        return 2 * EARTH_RADIUS_KM * Math.asin(Math.min(1, Math.sqrt(h)));
    }

    /** То же, но точками {lat, lng} — так удобнее планировщику. */
    function betweenPoints(from, to) {
        return haversineKm(from.lat, from.lng, to.lat, to.lng);
    }

    /** Зажать число в границы. Тоже жил тремя копиями. */
    function clamp(value, low, high) {
        return Math.max(low, Math.min(high, value));
    }

    return {
        EARTH_RADIUS_KM: EARTH_RADIUS_KM,
        DEG: DEG,
        haversineKm: haversineKm,
        betweenPoints: betweenPoints,
        clamp: clamp,
    };
})();
